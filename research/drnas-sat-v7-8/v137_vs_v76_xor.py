P="DRNAS-V137-V76-INDEPENDENT-48-XOR-PAIRED-20261101-v1"
SOURCE_SHA="e4f44436ef53682a514fbb852e876c5c0d0a2ee3"
MODES=("V137_Exact","V76_adaptive_guided","DRNAS_Legacy","Kissat404")
CAP=30.0;REPS=2;SHARDS=8
mini.CAP=CAP;mini.MEMORY_GIB=3
def ensure(ok,msg):
    if not ok:raise RuntimeError(msg)
def load(path):return json.loads(Path(path).read_text())
def save(path,obj):
    p=Path(path);p.parent.mkdir(parents=True,exist_ok=True)
    p.write_text(json.dumps(obj,sort_keys=True,indent=2)+"\n")
def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def selftest():
    newxor.selftest()
    exact.selftest()
    ensure(CAP==30.0 and REPS==2 and SHARDS==8,"Protocol changed")
    for i in range(48):
        entry,raw=newxor.make(i)
        n,clauses=exact.read_dimacs(raw)
        z=exact.decide(raw)
        ensure(z["path"]=="affine_exact" and z["status"]==entry["official_label"],
               "V13.7 failed to detect original XOR i="+str(i))
        ensure(exact.verify(n,clauses,z),"V13.7 GF2 certificate failed")
    print("V137_V76_SAME48_SELFTEST_PASS",flush=True)
def freeze(a):
    m=load(a.prior)
    ensure(m["protocol"]=="DRNAS-V761-XOR-REPEATS-AND-48-FROZEN-20261101-v1",
           "Wrong frozen V761 manifest")
    ensure(len(m["new_cases"])==48 and m["cap_seconds"]==CAP,"Sample changed")
    ensure(m["new_cases"]==[newxor.make(i)[0] for i in range(48)],
           "Exact new XOR sample mismatch")
    raw=Path(a.prior).read_bytes()
    Path(a.out).parent.mkdir(parents=True,exist_ok=True)
    Path(a.out).write_bytes(raw)
    print("V137_V76_SAME48_FREEZE_PASS",len(m["new_cases"]),sha(a.out),flush=True)
def exact_trial(cnf,seed,drnas,kissat,label):
    command=[sys.executable,str(Path(exact.__file__).resolve()),
             str(cnf.resolve()),"--drnas",str(Path(drnas).resolve()),
             "--kissat",str(Path(kissat).resolve()),"--seed",str(seed)]
    start=time.monotonic()
    try:
        proc=subprocess.run(command,timeout=CAP,capture_output=True,text=True,
                            errors="replace",preexec_fn=mini.memory_limit)
        seconds=time.monotonic()-start
        ensure(proc.returncode==0,"V13.7 failed: "+proc.stderr[-280:])
        lines=[line for line in proc.stdout.splitlines()
               if line.startswith("DRNAS_V137_RESULT\t")]
        ensure(len(lines)==1,"No unique V13.7 result")
        v=json.loads(lines[0].split("\t",1)[1])
        ensure(v["status"]==label,"V13.7 wrong SAT result")
        ensure(v["path"]=="affine_exact","V13.7 did not recognize pure XOR")
        n,clauses=exact.read_dimacs(cnf.read_bytes())
        ensure(exact.verify(n,clauses,v),"GF2 proof/model verification failure")
        ensure(seconds<=CAP,"Late result")
        return {"status":label,"seconds":round(seconds,6),
                "error":"","path":v["path"],"verified":True}
    except subprocess.TimeoutExpired:
        return {"status":"TIMEOUT","seconds":CAP,"error":"","path":"timeout",
                "verified":False}
    except Exception as e:
        return {"status":"ERROR","seconds":min(CAP,time.monotonic()-start),
                "error":str(e)[:320],"path":"error","verified":False}
def trial(mode,cnf,seed,label,a):
    if mode=="V137_Exact":
        return exact_trial(cnf,seed,a.legacy,a.kissat,label)
    if mode=="V76_adaptive_guided":
        x=old.trial(mode,cnf,seed,label,a.v76,a.legacy,a.kissat)
        return {"status":x["status"],"seconds":x["seconds"],
                "error":x["error"],"path":"cadical_v76","verified":False}
    x=mini.trial(mode,cnf,seed,a.legacy,a.kissat,label)
    return {"status":x["status"],"seconds":x["seconds"],
            "error":x["error"],"path":mode,"verified":False}
def run(a):
    m=load(a.manifest)
    ensure(m["protocol"]=="DRNAS-V761-XOR-REPEATS-AND-48-FROZEN-20261101-v1",
           "Wrong frozen manifest")
    ensure(0<=a.shard<SHARDS,"Bad shard")
    cases=m["new_cases"][a.shard::SHARDS];ensure(len(cases)==6,"Shard size drift")
    allowed=os.sched_getaffinity(0);os.sched_setaffinity(0,{min(allowed)})
    out=Path(a.out);out.mkdir(parents=True,exist_ok=True)
    cpu=next((x.split(":",1)[1].strip() for x in Path("/proc/cpuinfo").read_text().splitlines()
              if x.startswith("model name")),"unknown")
    import v136_symbolic
    save(out/"meta.json",{"protocol":P,"shard":a.shard,
        "manifest_sha256":sha(a.manifest),"ids":[x["id"] for x in cases],
        "cpu":cpu,"modes":MODES,"reps":REPS,"cap":CAP,
        "v137_blob_sha":a.source_sha,
        "binaries":{x:sha(getattr(a,x)) for x in ("v76","legacy","kissat")},
        "v137_fastpath_sha256":sha(exact.__file__),
        "v136_router_sha256":sha(v136_symbolic.__file__)})
    rows=[]
    for entry in cases:
        calc,raw=newxor.make(entry["index"])
        ensure(calc==entry,"Formula code/source identity drift")
        cnf=out/(entry["sha256"][:20]+".cnf");cnf.write_bytes(raw)
        ensure(sha(cnf)==entry["sha256"],"Input digest mismatch")
        attempts=[]
        for rep in range(REPS):
            seed=(7612026+int(entry["sha256"][:8],16)+1009*rep)%(2**32)
            order=list(MODES);random.Random(seed^13776).shuffle(order)
            for mode in order:
                x=trial(mode,cnf,seed,entry["official_label"],a)
                ensure(x["status"] in ("SAT","UNSAT","TIMEOUT"),
                       "Trial error: "+entry["id"]+" "+mode+" "+x["error"])
                ensure(x["status"]=="TIMEOUT" or x["status"]==entry["official_label"],
                       "Solver provided incorrect SAT/UNSAT")
                attempts.append({"mode":mode,"repetition":rep,"seed":seed,**x})
                print("V137V76_TRIAL",entry["id"],rep,mode,x["status"],x["seconds"],flush=True)
        rows.append({"id":entry["id"],"index":entry["index"],"sha256":entry["sha256"],
                    "label":entry["official_label"],"vertices":entry["graph_vertices"],
                    "trials":attempts})
        save(out/"rows.json",rows)
        cnf.unlink()
    ensure(len(rows)==6,"Unfinished benchmark")
    print("V137V76_SHARD_PASS",a.shard,len(rows),flush=True)
def aggregate(rows):
    p={m:[] for m in MODES};solved=Counter(); cases={}
    for entry in rows:
        pairs={(x["mode"],x["repetition"]):x for x in entry["trials"]}
        ensure(len(pairs)==8,"Duplicate/missing trial")
        case={"status":entry["label"],"vertices":entry["vertices"],"par2":{}}
        for mode in MODES:
            vals=[]
            for rep in range(REPS):
                x=pairs[(mode,rep)]
                ensure(x["status"]=="TIMEOUT" or x["status"]==entry["label"],
                       "Wrong answer after audit")
                ensure(x["status"]=="TIMEOUT" or 0<=x["seconds"]<=CAP+0.1,
                       "Trial wall time outside limit")
                if mode=="V137_Exact" and x["status"]!="TIMEOUT":
                    ensure(x["path"]=="affine_exact" and x["verified"],
                           "Unverified V13.7 proof")
                solved[mode]+=int(x["status"]!="TIMEOUT")
                cost=2*CAP if x["status"]=="TIMEOUT" else x["seconds"]
                vals.append(cost);p[mode].append(cost)
            case["par2"][mode]=round(statistics.mean(vals),6)
        cases[entry["id"]]=case
    return {"formulas":len(rows),"modes":{mode:{"solved":solved[mode],
        "attempts":len(rows)*REPS,"PAR2_s":round(statistics.mean(p[mode]),6)}
        for mode in MODES},"per_case":cases}
def audit(a):
    m=load(a.manifest);ensure(len(m["new_cases"])==48,"Wrong manifest size")
    rows=[];allbins=set();allcode=set();cpus=set()
    for shard in range(SHARDS):
        root=Path(a.combined)/f"v137v76-shard-{shard}"
        meta=load(root/"meta.json")
        expected=m["new_cases"][shard::SHARDS]
        part=load(root/"rows.json")
        ensure(meta["protocol"]==P and meta["shard"]==shard and
               meta["manifest_sha256"]==sha(a.manifest) and
               meta["ids"]==[x["id"] for x in expected],"Wrong shard provenance")
        ensure(len(part)==6 and [x["id"] for x in part]==[x["id"] for x in expected],
               "Incomplete rows")
        ensure(meta["v137_blob_sha"]==SOURCE_SHA,"V13.7 source changed")
        allbins.add(json.dumps(meta["binaries"],sort_keys=True))
        allcode.add((meta["v137_fastpath_sha256"],meta["v136_router_sha256"]))
        cpus.add(meta["cpu"]);rows.extend(part)
    ensure(len(allbins)==1 and len(allcode)==1,"Binary or code drift")
    ensure(len(rows)==48 and len({x["sha256"] for x in rows})==48,
           "Incomplete heldout formula set")
    index={x["id"]:x for x in m["new_cases"]}
    for row in rows:
        c=index[row["id"]]
        ensure(row["sha256"]==c["sha256"] and row["label"]==c["official_label"],
               "Formula digest and truth mismatch")
    stats={"all":aggregate(rows),
           "xor_unsat":aggregate([x for x in rows if x["label"]=="UNSAT"]),
           "xor_sat":aggregate([x for x in rows if x["label"]=="SAT"])}
    report={"protocol":P,"original_v761_manifest_sha256":sha(a.manifest),
        "source_git_blob":SOURCE_SHA,"summary":stats,"models":sorted(cpus),
        "binaries_sha256":json.loads(next(iter(allbins))),"rows":rows,
        "limitations":[
          "48 synthetic XOR formulas from V7.6.1, generated AFTER V13.7 implementation but from a known XOR family.",
          "Exactly same CNF SHA-256, two repetitions, 30s, 3GiB, pinned CPU and same runner for all four modes.",
          "V13.7 is an unchanged original Python process including startup and its own GF2 proof verification.",
          "V13.7 GF(2) solution is standard mathematical algorithm, not general polynomial SAT solving.",
          "Result is not official SAT Competition score; independent complex non-XOR real datasets still matter.",
          "Different runners may have different physical CPUs, but modes are paired per case on each runner."]}
    save(a.out,report)
    lines=["# Matched comparison: DRNAS V13.7 vs V7.6 (48 frozen XOR CNFs)","",
      "Known SAT/UNSAT from constructive proof, 2 repeats per solver, 30s 3GiB pinned CPU.",
      "All 48 formulas bytewise identical to V7.6.1, SHA verified; original V13.7 unchanged.",""]
    for name,group in stats.items():
        lines.extend([f"## {name}: {group['formulas']} instances","",
            "| Mode | Solved / attempts | PAR2 seconds |","|---|---:|---:|"])
        for mode in MODES:
            d=group["modes"][mode]
            lines.append(f"| {mode} | {d['solved']}/{d['attempts']} | {d['PAR2_s']:.6f} |")
        lines.append("")
    lines+=["## Scientific qualifications"]+["- "+v for v in report["limitations"]]
    Path(a.md).write_text("\n".join(lines)+"\n")
    print("V137V76_AUDIT_PASS",json.dumps(stats["all"]["modes"]),flush=True)
def main():
    p=argparse.ArgumentParser();s=p.add_subparsers(dest="mode",required=True)
    s.add_parser("selftest")
    x=s.add_parser("freeze")
    for name in ("prior","out"):x.add_argument("--"+name,required=True)
    x=s.add_parser("run")
    for name in ("manifest","v76","legacy","kissat","out","source_sha"):
        x.add_argument("--"+name,required=True)
    x.add_argument("--shard",type=int,required=True)
    x=s.add_parser("audit")
    for name in ("manifest","combined","out","md"):x.add_argument("--"+name,required=True)
    a=p.parse_args()
    {"selftest":selftest,"freeze":lambda:freeze(a),"run":lambda:run(a),
     "audit":lambda:audit(a)}[a.mode]()
if __name__=="__main__":main()
